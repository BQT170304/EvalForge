"""Experiment report generator for Markdown and JSON executive summaries."""

import uuid

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm import selectinload

from evalforge.models.db import EvaluationRunModel, ExperimentModel


class ExperimentReporter:
    """Formats experiment evaluation runs into executive Markdown and JSON evaluation reports."""

    def __init__(self, db: AsyncSession) -> None:
        self.db = db

    async def generate_markdown_report(self, experiment_id: uuid.UUID) -> str:
        """Generates a GitHub-flavored Markdown evaluation report for CI/CD gating and documentation."""
        stmt = (
            select(ExperimentModel)
            .where(ExperimentModel.id == experiment_id)
            .options(
                selectinload(ExperimentModel.evaluation_runs).selectinload(
                    EvaluationRunModel.results
                )
            )
        )
        result = await self.db.execute(stmt)
        exp = result.scalar_one_or_none()

        if not exp:
            raise ValueError(f"Experiment {experiment_id} not found")

        pass_pct = f"{(exp.pass_rate or 0.0) * 100:.1f}%"
        status_emoji = "✅ PASS" if (exp.pass_rate or 0.0) >= 0.8 else "❌ FAIL"

        lines = [
            f"# 📊 EvalForge Evaluation Report — {exp.name}",
            "",
            f"> **Status:** {status_emoji} | **Pass Rate:** `{pass_pct}` | **Dataset Version:** `{exp.dataset_version}`",
            "",
            "## 📈 Executive Summary",
            "",
            "| Metric Parameter | Value |",
            "| :--- | :--- |",
            f"| **Experiment ID** | `{exp.id}` |",
            f"| **Judge Model** | `{exp.judge_model}` |",
            f"| **Target Model** | `{exp.target_model or 'N/A'}` |",
            f"| **Prompt Version** | `{exp.prompt_version or 'default'}` |",
            f"| **Total Test Cases** | `{exp.total_entries}` |",
            f"| **Passed Cases** | `{exp.passed_entries}` |",
            f"| **Failed Cases** | `{exp.failed_entries}` |",
            f"| **Total Cost (USD)** | `${exp.total_cost_usd:.4f}` |",
            f"| **Duration** | `{exp.duration_seconds or 0:.2f}s` |",
            "",
            "## 🎯 Metrics Breakdown",
            "",
            "| Metric | Average Score | Pass Rate | Min | Max |",
            "| :--- | :--- | :--- | :--- | :--- |",
        ]

        scores = exp.summary_scores or {}
        for metric_name, data in scores.items():
            avg = f"{data.get('average', 0.0):.2f}"
            m_pass = f"{data.get('pass_rate', 0.0) * 100:.1f}%"
            min_s = f"{data.get('min', 0.0):.2f}"
            max_s = f"{data.get('max', 0.0):.2f}"
            lines.append(f"| `{metric_name}` | **{avg}** | {m_pass} | {min_s} | {max_s} |")

        # Failed test cases drill-down
        failed_runs = [r for r in exp.evaluation_runs if not r.overall_passed]
        if failed_runs:
            lines.extend(
                [
                    "",
                    f"## ⚠️ Failed Test Cases ({len(failed_runs)})",
                    "",
                ]
            )
            for idx, r in enumerate(failed_runs[:10], start=1):
                reasons = [res.reason for res in r.results if not res.passed and res.reason]
                reasons_str = "; ".join(reasons) if reasons else "Score below threshold"
                lines.extend(
                    [
                        f"### {idx}. Input: *{r.input[:100]}*",
                        f"- **Output:** {r.output[:150]}...",
                        f"- **Reason for Failure:** {reasons_str}",
                        "",
                    ]
                )

        lines.extend(
            [
                "---",
                "*Report automatically generated by [EvalForge](https://github.com/BQT170304/EvalForge)*",
            ]
        )

        return "\n".join(lines)
